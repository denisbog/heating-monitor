#!/usr/bin/env bash
# Build worker/.dev.vars from your existing ~/.config/monitoring/credentials.toml,
# generating a fresh API_TOKEN. Nothing is printed except the key names.
#
#   ./make-dev-vars.sh              # uses ~/.config/monitoring/credentials.toml
#   ./make-dev-vars.sh path/to.toml
#
# Then: ./set-secrets.sh && curl ... (see README)
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="${1:-$HOME/.config/monitoring/credentials.toml}"
OUT="$HERE/.dev.vars"

python3 - "$SRC" "$OUT" <<'PY'
import os, secrets, sys, tomllib

src, out = sys.argv[1], sys.argv[2]
if not os.path.exists(src):
    sys.exit(f"not found: {src}")

with open(src, "rb") as f:
    cfg = tomllib.load(f)

il = cfg.get("iletcomfort") or {}
came = cfg.get("cameconnect") or {}

# CAME client id/secret are public (baked into their web app bundle); fall back
# to the known values if the credentials file doesn't carry them.
CAME_CLIENT_ID = "58FnU0A4KqLYo3zJO1GMuYpTu74RyfnL"
CAME_CLIENT_SECRET = (
    "T23FhzVZCXUD87TwP21L3ALdJYcPGCCPSqQTjMrnwG5SwQY6w6xFa9hnidS9KkZb8MMUBJJC8U2UdpFqdUVjbXtzdNqUk9eDu72VF6YdKTq8Z8ULzmbcAvgEiNwzZq2x6RLxF7ewCqAMUcUBPEAXhJwqv7j6f3bxJZNZZmLpWn5b8MqVxwk6CNq0C6uVTrRJuwTEkY23Vpq5Atwyq0QatdMwcFDT7CFJgJs1DiBR3MmHX0fXE4gnvLiJEFG0LXfR"
)

rows = [
    ("ILETCOMFORT_REGION", il.get("region", "eu")),
    ("ILETCOMFORT_USERNAME", il.get("username", "")),
    ("ILETCOMFORT_PASSWORD", il.get("password", "")),
    ("CAMECONNECT_USERNAME", came.get("username", "")),
    ("CAMECONNECT_PASSWORD", came.get("password", "")),
    ("CAMECONNECT_CLIENT_ID", came.get("client_id") or CAME_CLIENT_ID),
    ("CAMECONNECT_CLIENT_SECRET", came.get("client_secret") or CAME_CLIENT_SECRET),
    ("API_TOKEN", secrets.token_hex(32)),
    # Read-only token: can read data but not trigger a collection. Deliberately
    # simple so it can be shared (dashboard, family member). Change at will.
    ("READ_TOKEN", os.environ.get("READ_TOKEN", "1013")),
]

lines = ["# generated by make-dev-vars.sh — do not commit"]
for k, v in rows:
    lines.append(f"{k}={v}")

fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("\n".join(lines) + "\n")

for k, v in rows:
    print(f"  {k:26} {'set' if v else 'EMPTY'}")
print(f"\nwrote {out} (mode 600)")
PY
